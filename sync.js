'use strict';
/* Sync engine: reads each day from Drive, merges it with the local day (merge.js), writes back what changed.
   Plain script: globalThis.Sync. All dependencies are injected (see tests/sync.test.js):
     Sync.create({ drive, getS, persist, uid, today, now?, specText?, windowDays? })
   Safety rules (spec-meal-tracker.md): local storage stays the offline source; a day is always read right before it is written;
   the first sync on a device (or after storage was wiped) pulls everything before it writes anything; a day that cannot be
   read as a whole (newer format, unreadable block) is never written; a write that races with another writer is retried. */
(function (root) {
  const SPEC_MARKER = '<!-- Managed by the Meal Tracker app.';
  const DAY_RE = /^(\d{4}-\d{2}-\d{2})\.md$/;
  const MAX_SUGGESTIONS = 50, KEEP_DAYS = 120, AHEAD_DAYS = 7;

  // ---------- settings.md (goals) ----------
  const GOAL_KEYS = ['kcal', 'p', 'c', 'f'];
  function parseSettings(text) {
    const lines = String(text ?? '').replace(/\r\n?/g, '\n').split('\n'), m = { pre: [], other: [], post: [], goals: null, hasBlock: false };
    const s = lines.findIndex(l => /^```\s*(yaml|yml)\s*$/i.test(l.trim()));
    const e = s < 0 ? -1 : lines.findIndex((l, i) => i > s && /^```\s*$/.test(l.trim()));
    if (s < 0 || e < 0) { m.pre = lines; return m; }
    m.hasBlock = true; m.pre = lines.slice(0, s); m.post = lines.slice(e + 1);
    const body = lines.slice(s + 1, e); let inGoals = false; const g = {};
    for (const l of body) {
      if (/^goals:\s*$/.test(l)) { inGoals = true; continue; }
      const kv = inGoals && /^ {2}(kcal|p|c|f|rev):\s*(-?\d+(?:\.\d+)?)\s*(?:#.*)?$/.exec(l);
      if (kv) { g[kv[1]] = Number(kv[2]); continue; }
      if (inGoals && /^ {2}\S/.test(l)) continue;      // unknown goal key: drop (the app owns this section)
      inGoals = false; m.other.push(l);
    }
    if (GOAL_KEYS.every(k => Number.isFinite(g[k]))) m.goals = { ...g, rev: Number.isFinite(g.rev) ? g.rev : 0 };
    return m;
  }
  function serializeSettings(m, goals) {
    const pre = m.pre.length && m.pre.some(l => l.trim()) ? m.pre : ['---', 'format: meal-settings/1', '---', '# Meal Tracker settings', 'Written by the app. Claude: read the goals below, do not edit this file.', ''];
    const block = ['```yaml', 'goals:', ...GOAL_KEYS.map(k => `  ${k}: ${Math.round(goals[k])}`), `  rev: ${goals.rev || 0}`, ...m.other, '```'];
    return [...pre, ...block, ...m.post].join('\n').replace(/\n*$/, '\n');
  }

  function create({ drive, getS, persist, uid, today, now = Date.now, specText = null, windowDays = 14 }) {
    const listeners = new Set();
    const info = { state: 'idle', lastError: null, warnings: [], lastSync: 0, blocked: {} };
    let busy = null, again = false, specDone = false;
    const S = () => getS();
    const st = () => { const s = S(); return s.sync ||= { synced: false, lastSync: 0, days: {}, suggestions: [] }; };
    const emit = () => listeners.forEach(f => { try { f(status()); } catch {} });
    const setState = (state, err = null) => { info.state = state; info.lastError = err; emit(); };

    // ---------- what is waiting to be pushed ----------
    const windowDates = (visible, wide) => {
      // Claude plans ahead, so the window reaches AHEAD_DAYS into the future (i < 0 counts forward from today).
      const out = new Set(), n = wide ? 90 : windowDays;
      for (let i = -AHEAD_DAYS; i < n; i++) out.add(addDaysISO(today(), -i));
      if (visible) out.add(visible);
      return out;
    };
    function addDaysISO(s, n) { const d = new Date(s + 'T12:00:00Z'); d.setUTCDate(d.getUTCDate() + n); return d.toISOString().slice(0, 10); }
    const sigOf = (date) => {
      const S_ = S(), local = S_.entries[date] || [], tombs = S_.tombstones?.[date] || {}, day = st().days[date];
      const cur = {}; for (const e of local) cur[e.id] = DayMerge.canon(DayFile.fromApp(e));
      if (!day) return local.length > 0;                                                  // never synced: pending if there is something to send
      const b = day.base || { entries: {}, tombs: {} };
      for (const id of Object.keys(cur)) if (!b.entries[id] || b.entries[id].canon !== cur[id]) return true;
      for (const id of Object.keys(b.entries)) if (!(id in cur)) return true;             // an entry we synced is gone locally (deleted)
      for (const id of Object.keys(tombs)) if (b.tombs[id] == null && b.entries[id]) return true;
      return false;
    };
    /** Days (in the sync window) with local changes not yet on Drive. */
    function pendingDays() {
      const S_ = S(), dates = new Set([...Object.keys(S_.entries), ...Object.keys(S_.tombstones || {}), ...Object.keys(st().days)]);
      const inWin = windowDates(null, !st().synced);
      return [...dates].filter(d => (inWin.has(d) || S_.entries[d]?.length) && !st().days[d]?.blocked && sigOf(d)).sort();
    }
    function status() {
      const s = st(), pending = pendingDays().length, goalsPending = goalsDirty();
      return { state: info.state, pending: pending + (goalsPending ? 1 : 0), lastSync: s.lastSync, lastError: info.lastError, warnings: [...info.warnings], blocked: { ...info.blocked }, suggestions: s.suggestions.length, synced: s.synced };
    }
    const goalsDirty = () => { const g = S().goals; return !!g.manual && (g.rev || 0) !== (st().goalsSyncedRev ?? -1); };

    // ---------- one day ----------
    async function syncDay(date, files, folderId, { readOnlyPass = false } = {}) {
      const name = `${date}.md`, S_ = S(); let group = files || [];
      if (!readOnlyPass && group.length > 1) {
        const { keep } = await drive.resolveDuplicates(group, texts => DayFile.serialize(DayMerge.unionModels(texts.map(DayFile.parse), uid)));
        info.warnings.push(`${name}: merged ${group.length} copies of the same day`); group = [keep];
      }
      const hasLocal = (S_.entries[date]?.length || 0) > 0 || Object.keys(S_.tombstones?.[date] || {}).length > 0;
      if (!group.length && !hasLocal) return { pulled: 0, pushed: 0 };
      for (let attempt = 0; attempt < 4; attempt++) {
        const file = group[0] || null, text = file ? await drive.readFile(file.id) : null, model = text != null ? DayFile.parse(text) : null;
        if (model?.readOnly) { st().days[date] = { ...(st().days[date] || {}), blocked: model.warnings[0] || 'unreadable' }; info.blocked[date] = st().days[date].blocked; return { blocked: true, pulled: 0, pushed: 0 }; }
        if (st().days[date]?.blocked) { delete st().days[date].blocked; delete info.blocked[date]; }
        const local = S_.entries[date] || [], tombs = S_.tombstones?.[date] || {}, base = st().days[date]?.base || null;
        const res = DayMerge.mergeDay({ date, local, localTombs: tombs, remote: model, base: readOnlyPass ? null : base, uid, now: now() });
        let pulled = 0;
        if (res.localChanged) {
          if (res.entries.length) S_.entries[date] = res.entries; else delete S_.entries[date];
          S_.tombstones ||= {}; if (Object.keys(res.tombs).length) S_.tombstones[date] = res.tombs; else delete S_.tombstones[date];
          pulled = 1;
        }
        for (const sg of res.suggestions) addSuggestion(sg);
        if (res.localChanged || res.suggestions.length) persist();
        if (readOnlyPass) return { pulled, pushed: 0 };
        if (!res.remoteNeedsUpdate) { st().days[date] = { fileId: file?.id, modified: file?.modifiedTime, base: DayMerge.makeBase(res.items) }; return { pulled, pushed: 0 }; }
        const out = model || DayFile.create(date, []); out.items = res.items;
        try {
          const w = await drive.writeFile({ id: file?.id, name, folderId, text: DayFile.serialize(out), expectedModifiedTime: file?.modifiedTime });
          let fin = w.file;
          if (w.duplicates?.length) { const r = await drive.resolveDuplicates([w.file, ...w.duplicates], texts => DayFile.serialize(DayMerge.unionModels(texts.map(DayFile.parse), uid))); fin = r.keep || fin; info.warnings.push(`${name}: another device created the same day at the same time; merged`); }
          st().days[date] = { fileId: fin.id, modified: fin.modifiedTime, base: DayMerge.makeBase(res.items) };
          return { pulled, pushed: 1 };
        } catch (e) {
          if (e.kind !== 'conflict') throw e;
          group = (await drive.findByName(folderId, name));    // changed under us: read again and re-merge
        }
      }
      throw Object.assign(new Error(`${name} keeps changing on Drive; will retry`), { kind: 'conflict' });
    }
    function addSuggestion(sg) {
      const list = st().suggestions, sig = JSON.stringify([sg.date, sg.id, sg.kind, sg.remote ? DayMerge.canon(sg.remote) : null]);
      if (list.some(x => JSON.stringify([x.date, x.id, x.kind, x.remote ? DayMerge.canon(x.remote) : null]) === sig)) return;
      list.push(sg); if (list.length > MAX_SUGGESTIONS) list.splice(0, list.length - MAX_SUGGESTIONS);
    }

    // ---------- goals (settings.md) ----------
    async function syncGoals(folderId) {
      const g = S().goals, { file } = await drive.locate(folderId, 'settings.md');
      const remoteText = file ? await drive.readFile(file.id) : null, rm = remoteText != null ? parseSettings(remoteText) : null, rg = rm?.goals;
      const lrev = g.rev || 0;
      if (rg && (rg.rev > lrev || (rg.rev === lrev && GOAL_KEYS.some(k => rg[k] !== g[k])))) {   // Drive is newer, or was edited by hand
        S().goals = { kcal: rg.kcal, p: rg.p, c: rg.c, f: rg.f, manual: true, rev: Math.max(rg.rev, lrev) }; st().goalsSyncedRev = S().goals.rev; persist(); return 'adopted';
      }
      if (!g.manual) { return 'skipped'; }                                    // never push the untouched defaults
      if (rg && rg.rev === lrev) { st().goalsSyncedRev = lrev; return 'unchanged'; }
      await drive.writeFile({ id: file?.id, name: 'settings.md', folderId, text: serializeSettings(rm || parseSettings(''), { ...g, rev: lrev }), expectedModifiedTime: file?.modifiedTime });
      st().goalsSyncedRev = lrev; return 'pushed';
    }

    // ---------- everything ----------
    async function run({ visibleDate } = {}) {
      info.warnings = []; setState('syncing');
      const s = st();
      try {
        const { folderId, warnings } = await drive.resolveFolders(); info.warnings.push(...warnings);
        if (specText && !specDone) { try { const t = await specText(); if (t) { await drive.syncSpecFile(folderId, 'FORMAT.md', t, SPEC_MARKER); specDone = true; } } catch (e) { if (e.kind === 'auth') throw e; } }
        const files = await drive.listFiles(folderId), groups = drive.groupByName(files), wide = !s.synced, win = windowDates(visibleDate, wide);
        const remoteDays = Object.keys(groups).map(n => DAY_RE.exec(n)?.[1]).filter(d => d && (win.has(d)));
        const pend = new Set(pendingDays());
        const localDays = [...new Set([...Object.keys(S().entries), ...Object.keys(S().tombstones || {})])].filter(d => win.has(d) || pend.has(d));
        const dates = [...new Set([...remoteDays, ...localDays, ...(visibleDate ? [visibleDate] : [])])].sort();
        if (wide) for (const d of dates) await syncDay(d, groups[`${d}.md`], folderId, { readOnlyPass: true });   // first sync: pull everything before writing anything
        let pulled = 0, pushed = 0;
        for (const d of dates) { const r = await syncDay(d, groups[`${d}.md`], folderId); pulled += r.pulled || 0; pushed += r.pushed || 0; }
        const goals = await syncGoals(folderId);
        for (const d of Object.keys(s.days)) if (d < addDaysISO(today(), -KEEP_DAYS)) delete s.days[d];
        s.synced = true; s.lastSync = now(); persist();
        setState('idle'); return { ok: true, pulled, pushed, goals };
      } catch (e) {
        const k = e.kind;
        setState(k === 'auth' ? 'auth' : k === 'network' ? 'offline' : 'error', e.message); persist();
        return { ok: false, kind: k, error: e.message };
      }
    }
    /** Run a sync; calls made while one is running are folded into one follow-up run. */
    function syncNow(opts = {}) {
      if (busy) { again = opts; return busy; }
      busy = run(opts).then(async r => { busy = null; if (again && r.ok) { const o = again; again = false; return syncNow(o); } again = false; return r; });
      return busy;
    }
    const onStatus = cb => { listeners.add(cb); return () => listeners.delete(cb); };
    const dismissSuggestion = i => { st().suggestions.splice(i, 1); persist(); emit(); };
    return { syncNow, status, onStatus, pendingDays, dismissSuggestion, parseSettings, serializeSettings };
  }
  root.Sync = { create, parseSettings, serializeSettings, SPEC_MARKER };
})(typeof globalThis !== 'undefined' ? globalThis : this);
